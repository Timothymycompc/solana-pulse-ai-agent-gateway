#!/usr/bin/env python3
"""Regenerates server/output-declarations.generated.ts: what each paid tool's answer always contains.

Needs two JSON files in a folder (read-only queries on the pulse database, e.g. with db-look):
  always.json  {tool: {"answers": n, "always": [keys]}}: top-level keys found in EVERY successful HTTP answer
               (service_usage, status 200, object output without the log's "truncated" marker, last 30 days).
  outs.json    {tool: output}: the latest successful answer to the tool's own listing example (LISTING_EXAMPLES),
               so examples show Pulse's example data, never a caller's.
  listing.json LISTING_EXAMPLES as JSON (npx tsx -e 'import("./server/x402.ts").then(m=>console.log(JSON.stringify(m.LISTING_EXAMPLES)))')
Usage: python3 scripts/output-declarations.py <folder> server/output-declarations.generated.ts
"""
S = sys.argv[1]; out_path = sys.argv[2]
outs = json.load(open(S + '/outs.json')); always = json.load(open(S + '/always.json'))
def trim(v, depth=0):
    if isinstance(v, str): return v if len(v) <= 100 else v[:100] + "…"
    if isinstance(v, list): return [trim(x, depth + 1) for x in v[:1]]
    if isinstance(v, dict):
        if depth >= 2: return {k: trim(x, depth + 1) for k, x in list(v.items())[:4]}
        return {k: trim(x, depth + 1) for k, x in v.items()}
    return v
decl = {}
for tool in sorted(outs):
    req = always[tool]['always']
    missing = [k for k in req if k not in outs[tool]]
    assert not missing, (tool, missing)
    ex = {k: trim(outs[tool][k]) for k in req}
    s = json.dumps(ex)
    while len(s) > 1500:  # shorten the longest values further until it fits
        k = max(ex, key=lambda k: len(json.dumps(ex[k])))
        v = ex[k]
        ex[k] = ([] if isinstance(v, list) else {} if isinstance(v, dict) else (v[:40] + "…" if isinstance(v, str) else v))
        if json.dumps(ex) == s: break
        s = json.dumps(ex)
    decl[tool] = {"answers": always[tool]['answers'], "required": req, "example": ex}
    print(f"{tool:14} answers={always[tool]['answers']:6} keys={len(req):2} example_bytes={len(s)}", file=sys.stderr)
ts = f"""// GENERATED by scripts/output-declarations.py on 2026-11-22. Do not edit by hand; rerun it (see that file).
// What each paid tool's answer always contains, declared in its 402 (x402 Bazaar extension, info.output) so monitors
// like vet402 can check paid answers (their "L2" check: top-level keys the declaration marks as required).
// required: the top-level keys found in EVERY successful HTTP answer in Pulse's usage log for the 30 days to
// 2026-11-22 ("answers" = how many). Keys missing from even one answer are left out, because a declared key that is
// missing counts against the tool.
// example: a real answer to the tool's own listing example (LISTING_EXAMPLES), keeping only the required keys;
// arrays keep their first item and long text is shortened with "…", to keep the 402 small.
export const OUTPUT_DECLARATIONS: Record<string, {{ answers: number; required: string[]; example: Record<string, unknown> }}> = {json.dumps(decl, indent=2, ensure_ascii=False)};
"""
open(out_path, 'w').write(ts)
