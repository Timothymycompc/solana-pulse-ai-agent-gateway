// Writes agent-kit/src/tools.generated.ts, the Solana Agent Kit plugin's tool list, from the same registry as MCP, the
// docs and /openapi.json, so the plugin can't drift from what runs. The plugin uses zod 3 (Agent Kit's), so each input
// schema is emitted as zod 3 source from its JSON schema. Usage: npm run agent-kit (tests/agent-kit.test.ts checks
// the committed file is current).
import fs from "fs";
import path from "path";
import { z } from "zod";
import { TOOLS } from "../server/tools";
import { FREE_CALLS_PER_TOOL, priceOf } from "../server/pricing";
import { VERSION } from "../server/version";

type Schema = Record<string, any>;
const lit = (v: unknown) => JSON.stringify(v);

// JSON schema (the subset the tool inputs use) to zod 3 source.
export function zodSource(s: Schema, required = true): string {
  let out: string;
  if (s.anyOf) out = `z.union([${s.anyOf.map((x: Schema) => zodSource(x)).join(", ")}])`;
  else if ("const" in s) out = `z.literal(${lit(s.const)})`;
  else if (s.enum) out = `z.enum([${s.enum.map(lit).join(", ")}])`;
  else if (s.type === "string") out = `z.string()${s.minLength !== undefined ? `.min(${s.minLength})` : ""}${s.maxLength !== undefined ? `.max(${s.maxLength})` : ""}`;
  else if (s.type === "integer" || s.type === "number") out = `z.number()${s.type === "integer" ? ".int()" : ""}${s.minimum !== undefined ? `.min(${s.minimum})` : ""}${s.maximum !== undefined ? `.max(${s.maximum})` : ""}`;
  else if (s.type === "boolean") out = "z.boolean()";
  else if (s.type === "object" && s.properties) {
    const req = new Set<string>(s.required ?? []);
    out = `z.object({ ${Object.entries(s.properties).map(([k, v]) => `${k}: ${zodSource(v as Schema, req.has(k))}`).join(", ")} })`;
  } else if (s.type === "object" && s.additionalProperties) out = `z.record(${zodSource(s.additionalProperties)})`;
  else out = "z.any()";
  if (s.description) out += `.describe(${lit(s.description)})`;
  if (s.default !== undefined) out += `.default(${lit(s.default)})`;
  else if (!required) out += ".optional()";
  return out;
}

// The usage line's first {...} is a real example call ("{"token": "SOL", "amount": "0.5"} gives 500000000").
function exampleInput(usage: string): Record<string, unknown> {
  const start = usage.indexOf("{");
  for (let end = usage.length; end > start; end = usage.lastIndexOf("}", end - 1)) {
    try { return JSON.parse(usage.slice(start, end + 1)); } catch { /* try a shorter span */ }
  }
  return {};
}

export function agentKitSource(): string {
  const entries = TOOLS.map((t) => {
    const { $schema, ...schema } = z.toJSONSchema(z.object(t.inputs), { io: "input", unrepresentable: "any" }) as Schema;
    const price = priceOf(t.name);
    return `  {
    name: ${lit(t.name)},
    title: ${lit(t.title)},
    description: ${lit(`${t.useWhen} ${t.description}`)},
    price: ${lit(price ? `${price} USDC per call after ${FREE_CALLS_PER_TOOL} free calls a day` : "free")},
    example: ${lit(exampleInput(t.usage))},
    schema: ${zodSource(schema)},
  },`;
  });
  return `// Generated by npm run agent-kit in solana-pulse-ai-agent-gateway from the live tool registry. Do not edit by hand.
import { z } from "zod";

export const PULSE_VERSION = ${lit(VERSION)};

export const TOOLS = [
${entries.join("\n")}
] as const;
`;
}

if (process.argv[1]?.endsWith("agent-kit.ts")) {
  const out = path.resolve("agent-kit/src/tools.generated.ts");
  fs.writeFileSync(out, agentKitSource());
  console.log(`Wrote ${out}`);
}
